    fig, ax = plt.subplots(figsize=(7.2, 1.95), dpi=150)
    fig.patch.set_facecolor("#FFFFFF")
    ax.set_facecolor("#FAFAFC")

    if not df_cf_comp.empty and "year" in df_cf_comp.columns:
        df_sorted = df_cf_comp.sort_values("year").tail(5)
