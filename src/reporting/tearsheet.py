def generate_company_tearsheet(
    company_id: str,
    db_path: Path | str = DEFAULT_DB_PATH,
    reports_dir: Path | str = DEFAULT_REPORTS_DIR,
    output_dir: Path | str = DEFAULT_TEARSHEETS_DIR,
) -> Path:
    """Generate a 2-page PDF tearsheet for a single company.

    Args:
        company_id (str): NSE ticker symbol.
        db_path (Path | str): Path to SQLite database.
        reports_dir (Path | str): Base reports directory path.
        output_dir (Path | str): Output directory for saved tearsheets.

    Returns:
        Path: Absolute path to the generated company tearsheet PDF.
    """
    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / f"{company_id}_tearsheet.pdf"

    conn = sqlite3.connect(str(db_path))

    # Company info
    comp_row = pd.read_sql_query(
        f"""SELECT c.id as company_id, c.company_name, c.company_logo,
                   s.broad_sector, p.peer_group_name
            FROM companies c
            LEFT JOIN sectors s ON c.id = s.company_id
            LEFT JOIN peer_groups p ON c.id = p.company_id
            WHERE c.id = '{company_id}'""",
        conn,
    )
    if comp_row.empty:
        raise ValueError(f"Company {company_id} not found in database")
    c_dict = comp_row.iloc[0].to_dict()

    # Ratios
    ratios_df = pd.read_sql_query(
        """SELECT r.company_id, r.year,
                  r.return_on_equity_pct as roe,
                  r.return_on_capital_employed_pct as roce,
                  r.operating_profit_margin_pct as operating_profit_margin,
                  r.debt_to_equity,
                  r.revenue_cagr_3yr,
                  r.free_cash_flow_cr,
                  s.broad_sector, p.peer_group_name
           FROM financial_ratios r
           JOIN sectors s ON r.company_id = s.company_id
           JOIN peer_groups p ON r.company_id = p.company_id
           WHERE r.year LIKE '%-03'
           AND r.year = (SELECT MAX(r2.year) FROM financial_ratios r2
                         WHERE r2.company_id = r.company_id AND r2.year LIKE '%-03')""",
        conn,
    )

    sc_excel = Path(reports_dir) / "screener_output.xlsx"
    if sc_excel.exists():
        sc_df = pd.read_excel(sc_excel, sheet_name="Summary")
        sc_scores = sc_df[["company_id", "composite_ranking_score"]].rename(
            columns={"composite_ranking_score": "composite_score"}
        )
        ratios_df = ratios_df.merge(sc_scores, on="company_id", how="left")
    else:
        ratios_df["composite_score"] = None

    val_excel = Path(reports_dir) / "valuation_summary.xlsx"
    if val_excel.exists():
        val_df = pd.read_excel(val_excel, sheet_name="Valuation Summary").set_index(
            "company_id"
        )
        val_pes = val_df[["pe_ratio"]].reset_index()
        ratios_df = ratios_df.merge(val_pes, on="company_id", how="left")
        v_row = val_df.loc[company_id].to_dict() if company_id in val_df.index else {}
    else:
        val_df = pd.DataFrame()
        v_row = {}

    ratio_fields = [
        "roe",
        "roce",
        "debt_to_equity",
        "revenue_cagr_3yr",
        "composite_score",
        "operating_profit_margin",
    ]
    sector_meds_all = (
        ratios_df.groupby("broad_sector")[ratio_fields].median().to_dict(orient="index")
    )
    bsector = c_dict.get("broad_sector", "")
    sec_meds = sector_meds_all.get(bsector, {})

    target_ratio = ratios_df[ratios_df["company_id"] == company_id]
    r_dict = target_ratio.iloc[0].to_dict() if not target_ratio.empty else {}

    # P&L and CF
    df_pl = pd.read_sql_query(
        f"SELECT * FROM profitandloss WHERE company_id = '{company_id}' AND year LIKE '%-03'",
        conn,
    )
    df_cf = pd.read_sql_query(
        f"SELECT * FROM cashflow WHERE company_id = '{company_id}' AND year LIKE '%-03'",
        conn,
    )

    # Pros and Cons
    pc_csv = Path(reports_dir) / "pros_cons_generated.csv"
    if pc_csv.exists():
        pc_df = pd.read_csv(pc_csv)
        c_pros = pc_df[(pc_df["company_id"] == company_id) & (pc_df["type"] == "pro")][
            "text"
        ].tolist()
        c_cons = pc_df[(pc_df["company_id"] == company_id) & (pc_df["type"] == "con")][
            "text"
        ].tolist()
    else:
        c_pros, c_cons = [], []

    # Peer group subset
    pgroup = c_dict.get("peer_group_name", "")
    peers_sub = ratios_df[ratios_df["peer_group_name"] == pgroup]

    # Capital Allocation
    cap_csv = REPO_ROOT / "data" / "processed" / "capital_allocation.csv"
    if cap_csv.exists():
        cap_df = pd.read_csv(cap_csv)
        cap_match = cap_df[cap_df["company_id"] == company_id].sort_values("year")
        cap_label = (
            cap_match.iloc[-1].get("pattern_label", "Balanced Capital Allocation")
            if not cap_match.empty
            else "Balanced Capital Allocation"
        )
    else:
        cap_label = "Balanced Capital Allocation"

    conn.close()

    build_tearsheet_pdf(
        company_id=company_id,
        comp_row=c_dict,
        latest_ratios=r_dict,
        sector_medians=sec_meds,
        df_pl_comp=df_pl,
        df_cf_comp=df_cf,
        pros_list=c_pros,
        cons_list=c_cons,
        peers_df=peers_sub,
        val_row=v_row,
        cap_alloc_label=cap_label,
        output_pdf_path=out_path,
    )

    return out_path


def generate_all_tearsheets(
    db_path: Path | str = DEFAULT_DB_PATH,
    reports_dir: Path | str = DEFAULT_REPORTS_DIR,
    output_dir: Path | str = DEFAULT_TEARSHEETS_DIR,
) -> dict[str, Any]:
    """Preload datasets in bulk and generate 2-page tearsheets for all 92 companies.

    Args:
        db_path (Path | str): Path to SQLite database.
        reports_dir (Path | str): Base reports directory path.
        output_dir (Path | str): Destination directory for generated PDF files.

    Returns:
        dict[str, Any]: Batch generation summary metrics including success counts and durations.
    """
    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    conn = sqlite3.connect(str(db_path))

    # 1. Companies
    companies_df = pd.read_sql_query(
        """SELECT c.id as company_id, c.company_name, c.company_logo,
                  s.broad_sector, p.peer_group_name
           FROM companies c
           LEFT JOIN sectors s ON c.id = s.company_id
           LEFT JOIN peer_groups p ON c.id = p.company_id
           ORDER BY c.id""",
        conn,
    )

    # 2. Latest ratios
    ratios_df = pd.read_sql_query(
        """SELECT r.company_id, r.year,
                  r.return_on_equity_pct as roe,
                  r.return_on_capital_employed_pct as roce,
                  r.operating_profit_margin_pct as operating_profit_margin,
                  r.debt_to_equity,
                  r.revenue_cagr_3yr,
                  r.free_cash_flow_cr,
                  s.broad_sector, p.peer_group_name
           FROM financial_ratios r
           JOIN sectors s ON r.company_id = s.company_id
           JOIN peer_groups p ON r.company_id = p.company_id
           WHERE r.year LIKE '%-03'
           AND r.year = (SELECT MAX(r2.year) FROM financial_ratios r2
                         WHERE r2.company_id = r.company_id AND r2.year LIKE '%-03')""",
        conn,
    )

    sc_excel = Path(reports_dir) / "screener_output.xlsx"
    if sc_excel.exists():
        sc_df = pd.read_excel(sc_excel, sheet_name="Summary")
        sc_scores = sc_df[["company_id", "composite_ranking_score"]].rename(
            columns={"composite_ranking_score": "composite_score"}
        )
        ratios_df = ratios_df.merge(sc_scores, on="company_id", how="left")
    else:
        ratios_df["composite_score"] = None

    val_excel = Path(reports_dir) / "valuation_summary.xlsx"
    if val_excel.exists():
        val_df = pd.read_excel(val_excel, sheet_name="Valuation Summary").set_index(
            "company_id"
        )
        val_pes = val_df[["pe_ratio"]].reset_index()
        ratios_df = ratios_df.merge(val_pes, on="company_id", how="left")
    else:
        val_df = pd.DataFrame()

    ratio_fields = [
        "roe",
        "roce",
        "debt_to_equity",
        "revenue_cagr_3yr",
        "composite_score",
        "operating_profit_margin",
    ]
    sector_medians_all = (
        ratios_df.groupby("broad_sector")[ratio_fields].median().to_dict(orient="index")
    )

    # Pros and Cons
    pc_csv = Path(reports_dir) / "pros_cons_generated.csv"
    pc_df = pd.read_csv(pc_csv) if pc_csv.exists() else pd.DataFrame()

    # Capital Allocation
    cap_csv = REPO_ROOT / "data" / "processed" / "capital_allocation.csv"
    if cap_csv.exists():
        cap_df = pd.read_csv(cap_csv)
        cap_latest = (
            cap_df.sort_values("year")
            .groupby("company_id")
            .last()
            .to_dict(orient="index")
        )
    else:
        cap_latest = {}

    # Bulk P&L and CF
    pl_all = pd.read_sql_query(
        "SELECT * FROM profitandloss WHERE year LIKE '%-03'", conn
    )
    cf_all = pd.read_sql_query("SELECT * FROM cashflow WHERE year LIKE '%-03'", conn)
    conn.close()

    total_companies = len(companies_df)
    logger.info("Starting tearsheet generation for %d companies...", total_companies)

    results: list[dict[str, Any]] = []
    failures: list[dict[str, str]] = []

    for idx, (_, comp_row) in enumerate(companies_df.iterrows(), start=1):
        cid = comp_row["company_id"]
        c_dict = comp_row.to_dict()
        bsector = c_dict.get("broad_sector", "")
        sec_meds = sector_medians_all.get(bsector, {})

        c_ratios = ratios_df[ratios_df["company_id"] == cid]
        r_dict = c_ratios.iloc[0].to_dict() if not c_ratios.empty else {}

        c_pl = pl_all[pl_all["company_id"] == cid]
        c_cf = cf_all[cf_all["company_id"] == cid]

        if not pc_df.empty:
            c_pros = pc_df[(pc_df["company_id"] == cid) & (pc_df["type"] == "pro")][
                "text"
            ].tolist()
            c_cons = pc_df[(pc_df["company_id"] == cid) & (pc_df["type"] == "con")][
                "text"
            ].tolist()
        else:
            c_pros, c_cons = [], []

        pgroup = c_dict.get("peer_group_name", "")
        peers_sub = ratios_df[ratios_df["peer_group_name"] == pgroup]

        v_row = val_df.loc[cid].to_dict() if cid in val_df.index else {}
        cap_info = cap_latest.get(cid, {})
        cap_label = cap_info.get("pattern_label", "Balanced Capital Allocation")

        out_pdf = out_dir / f"{cid}_tearsheet.pdf"

        try:
            build_tearsheet_pdf(
                company_id=cid,
                comp_row=c_dict,
                latest_ratios=r_dict,
                sector_medians=sec_meds,
                df_pl_comp=c_pl,
                df_cf_comp=c_cf,
                pros_list=c_pros,
                cons_list=c_cons,
                peers_df=peers_sub,
                val_row=v_row,
                cap_alloc_label=cap_label,
                output_pdf_path=out_pdf,
            )

            fsize = out_pdf.stat().st_size
            results.append(
                {
                    "company_id": cid,
                    "status": "SUCCESS",
                    "file_size": fsize,
                    "path": str(out_pdf),
                }
            )
            if idx % 10 == 0 or idx == total_companies:
                print(
                    f"Progress: [{idx}/{total_companies}] {cid} generated ({fsize:,} bytes)"
                )
        except Exception as e:
            logger.exception("Failed to generate tearsheet for %s", cid)
            failures.append({"company_id": cid, "reason": str(e)})

    sizes = [r["file_size"] for r in results]
    min_size = min(sizes) if sizes else 0
    max_size = max(sizes) if sizes else 0

    summary = {
        "total_attempted": total_companies,
        "total_success": len(results),
        "total_failed": len(failures),
        "failures": failures,
        "min_size_bytes": min_size,
        "max_size_bytes": max_size,
        "output_dir": str(out_dir),
    }

    print(
        f"Completed: {len(results)}/{total_companies} generated successfully. "
        f"Size range: {min_size:,} to {max_size:,} bytes. Failures: {len(failures)}"
    )

    return summary


